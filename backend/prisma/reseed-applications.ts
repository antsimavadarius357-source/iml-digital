async function run() {
  const agent = await prisma.user.findFirst({ where: { role: { code: 'AGENT' } } });
  const agentId = agent?.id || null;

  // Récupérer les bénéficiaires existants pour les lier
  const beneficiaries = await prisma.beneficiary.findMany();
  const benByCompany = new Map<string, string>();
  for (const b of beneficiaries) {
    if (b.companyName) benByCompany.set(b.companyName.toLowerCase().trim(), b.id);
  }

  console.log(`Insertion de ${CANDIDATES_DATA.length} candidatures...`);

  let count = 0;
  for (const item of CANDIDATES_DATA) {
    const createdAt = new Date(Date.now() - item.daysAgo * 86400_000);
    const submittedAt = new Date(createdAt.getTime() + 10 * 60_000);

    // Vérifier si un bénéficiaire correspond
    const benId = benByCompany.get(item.companyName.toLowerCase().trim()) || null;

    await prisma.application.create({
      data: {
        status: item.status,
        submittedAt: item.status !== ApplicationStatus.BROUILLON ? submittedAt : null,
        createdAt,
        updatedAt: createdAt,
        assignedAgentId: agentId,
        evaluationNotes: item.evaluationNotes,
        beneficiaryId: benId,
        applicantData: {
          firstName: item.firstName,
          lastName: item.lastName,
          email: item.email,
          phone: item.phone,
          city: item.city,
          companyName: item.companyName,
          structureType: item.structureType,
          hasVideoEquipment: true,
          interviewPreference: 'HYBRIDE',
        },
        projectData: {
          title: item.projectTitle,
          sector: item.sector,
          description: item.description,
          stage: item.stage,
        },
      },
    });
    count++;
  }

  const total = await prisma.application.count();
  console.log(`✅ Succès : ${count} candidatures créées. Total en base : ${total}`);
}

run()
  .catch(console.error)
  .finally(() => prisma.$disconnect());

